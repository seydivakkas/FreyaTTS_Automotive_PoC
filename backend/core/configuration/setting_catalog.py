class SettingCatalog:
    """Immutable catalog of all 77 registered Freya settings and their legacy aliases."""

    def __init__(self, specs: tuple[SettingSpec, ...] = _SPECS) -> None:
        by_key: dict[str, SettingSpec] = {}
        alias_to_key: dict[str, str] = {}
        for spec in specs:
            if spec.key in by_key:
                raise ValueError(f"Duplicate setting key: {spec.key}")
            by_key[spec.key] = spec
            for alias in spec.legacy_aliases:
                norm_alias = alias.strip().upper()
                if norm_alias in alias_to_key and alias_to_key[norm_alias] != spec.key:
                    raise ValueError(
                        f"Alias collision for {norm_alias}: {alias_to_key[norm_alias]} vs {spec.key}"
                    )
                alias_to_key[norm_alias] = spec.key
        self._specs = MappingProxyType(by_key)
        self._alias_to_key = MappingProxyType(alias_to_key)

    @property
    def specs(self) -> Mapping[str, SettingSpec]:
        return self._specs

    @property
    def alias_map(self) -> Mapping[str, str]:
        return self._alias_to_key

    def __len__(self) -> int:
        return len(self._specs)

    def __contains__(self, key: str) -> bool:
        return key in self._specs

    def get(self, key: str) -> SettingSpec | None:
        return self._specs.get(key)

    def resolve_key(self, raw_key: str) -> tuple[str, str | None] | None:
        if raw_key in self._specs:
            return raw_key, None
        lower = raw_key.lower()
        if lower in self._specs:
            alias = raw_key if raw_key != lower else None
            return lower, alias
        canonical = self._alias_to_key.get(raw_key.strip().upper())
        if canonical is not None:
            return canonical, raw_key
        return None

    def keys_by_sensitivity(self, sensitivity: SensitivityLevel) -> tuple[str, ...]:
        return tuple(k for k, v in self._specs.items() if v.sensitivity == sensitivity)


SETTING_CATALOG = SettingCatalog()
